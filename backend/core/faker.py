ROLES = ["Пострадавший", "Очевидец", "Родственник", "Знакомый", "Сотрудник"]
CAR_LETTERS = "АВЕКМНОРСТУХ"
MOSCOW_REGIONS = ["77", "97", "99", "177", "197", "199", "777", "797", "799"]


class FakeDataGenerator:
    """Изолированный детерминированный генератор псевдослучайных данных."""

    _addresses_cache: Optional[List[dict]] = None

    def __init__(self, seed: Optional[int] = None):
        self.random = random.Random(seed)

    @classmethod
    def _load_addresses(cls) -> List[dict]:
        if cls._addresses_cache is None:
            base_dir = Path(__file__).resolve().parent.parent.parent
            candidates = [
                base_dir / "data" / "moscow_112_addresses.json",
                Path.cwd() / "data" / "moscow_112_addresses.json",
            ]
            loaded_data = None
            for p in candidates:
                if p.is_file():
                    with open(p, "r", encoding="utf-8") as f:
                        loaded_data = json.load(f)
                    break

            if loaded_data is None:
                raise FileNotFoundError("moscow_112_addresses.json not found in data directory")

            cls._addresses_cache = loaded_data

        return cls._addresses_cache

    def generate_person(self) -> GeneratedPerson:
        """Генерирует согласованное ФИО (мужское или женское)."""
        gender = self.random.choice(["male", "female"])
        if gender == "male":
            first_name = self.random.choice(MALE_FIRST_NAMES)
            last_name = self.random.choice(MALE_LAST_NAMES)
            middle_name = self.random.choice(MALE_MIDDLE_NAMES)
        else:
            first_name = self.random.choice(FEMALE_FIRST_NAMES)
            last_name = self.random.choice(FEMALE_LAST_NAMES)
            middle_name = self.random.choice(FEMALE_MIDDLE_NAMES)

        return GeneratedPerson(
            first_name=first_name,
            last_name=last_name,
            middle_name=middle_name,
            gender=gender,
        )

    def generate_role(self) -> str:
        """Возвращает одну из стандартных ролей заявителя."""
        return self.random.choice(ROLES)

    def generate_phone(self) -> str:
        """Генерирует мобильный телефон в формате +79XXXXXXXXX (12 символов)."""
        digits = "".join(self.random.choice("0123456789") for _ in range(9))
        return f"+79{digits}"

    def generate_car_plate(self) -> str:
        """
        Генерирует автомобильный номер московского региона:
        буква - 3 цифры - 2 буквы - пробел - регион (например: А123ВЕ 77).
        """
        c1 = self.random.choice(CAR_LETTERS)
        digits = f"{self.random.randint(0, 999):03d}"
        c2 = self.random.choice(CAR_LETTERS)
        c3 = self.random.choice(CAR_LETTERS)
        region = self.random.choice(MOSCOW_REGIONS)
        return f"{c1}{digits}{c2}{c3} {region}"

    def generate_address(self) -> GeneratedAddress:
        """Лениво загружает и возвращает случайный адрес из базы данных Москвы."""
        addresses = self._load_addresses()
        item = self.random.choice(addresses)
        corpus = item.get("corpus")
        structure = item.get("structure")

        return GeneratedAddress(
            city=str(item.get("city", "Москва")),
            street=str(item.get("street", "")),
            house=str(item.get("house", "")),
            corpus=str(corpus) if corpus else None,
            structure=str(structure) if structure else None,
            full_address=str(item.get("full_address", "")),
            lat=float(item.get("lat", 0.0)),
            lon=float(item.get("lon", 0.0)),
            apartment=str(self.random.randint(1, 300)) if self.random.random() > 0.3 else None,
            floor=str(self.random.randint(1, 25)) if self.random.random() > 0.4 else None,
            entrance=str(self.random.randint(1, 10)) if self.random.random() > 0.5 else None,
            intercom=str(self.random.randint(1, 300)) if self.random.random() > 0.5 else None,
        )
