#!/usr/bin/env python3
"""Resolve and hash the actual Python 3.11 Linux install graph, including transitives."""
import json
from pathlib import Path
import platform
import subprocess
import sys
import tempfile


def main():
    if sys.version_info[:2] != (3, 11) or platform.system() != 'Linux' or platform.machine() != 'x86_64':
        raise SystemExit('Generate the deployment lock on Python 3.11 / Linux x86_64')
    root = Path(__file__).resolve().parents[2]
    with tempfile.TemporaryDirectory(prefix='112-lock-') as directory:
        report = Path(directory) / 'resolution.json'
        subprocess.run([sys.executable, '-m', 'pip', 'install', '--dry-run', '--ignore-installed',
                        '--report', str(report), '-r', str(root / 'backend/requirements/runtime.in')], check=True)
        data = json.loads(report.read_text())
        lines = ['# Generated by python3.11 backend/scripts/lock_dependencies.py',
                 '# Target: Linux x86_64, CPython 3.11. Use --require-hashes. All runtime transitives are pinned.']
        for item in sorted(data['install'], key=lambda item: item['metadata']['name'].lower()):
            sha = item['download_info']['archive_info']['hashes']['sha256']
            lines.append(f"{item['metadata']['name']}=={item['metadata']['version']} --hash=sha256:{sha}")
        (root / 'backend/requirements/runtime.lock').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
